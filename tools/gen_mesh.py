"""Generate a (p, q) torus-knot tube as a Wavefront OBJ (used by scenes/hero_knot.json).

    python tools/gen_mesh.py [out.obj] [segments] [sides]

Defaults: assets/models/torus_knot.obj, 360 segments x 24 sides
= 8,640 vertices and 17,280 triangles. Uses only the standard library.
"""
import math
import os
import sys

P, Q = 2, 3            # winds P times around the axis and Q times through the hole
KNOT_R, KNOT_r = 1.0, 0.4
TUBE = 0.22


def curve(t):
    a = KNOT_R + KNOT_r * math.cos(Q * t)
    return (a * math.cos(P * t), KNOT_r * math.sin(Q * t), a * math.sin(P * t))


def sub(a, b):
    return (a[0] - b[0], a[1] - b[1], a[2] - b[2])


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def norm(a):
    l = math.sqrt(a[0] ** 2 + a[1] ** 2 + a[2] ** 2)
    return (a[0] / l, a[1] / l, a[2] / l)


def main(out, segments, sides):
    verts = []
    for i in range(segments):
        t = 2 * math.pi * i / segments
        c = curve(t)
        tangent = norm(sub(curve(t + 1e-4), curve(t - 1e-4)))
        # Frame from the curve's offset to the knot's centre line (smooth for a torus knot)
        radial = norm((c[0], 0.0, c[2]))
        b = norm(cross(tangent, radial))
        n = cross(b, tangent)
        for j in range(sides):
            a = 2 * math.pi * j / sides
            ca, sa = math.cos(a) * TUBE, math.sin(a) * TUBE
            verts.append((c[0] + ca * n[0] + sa * b[0], c[1] + ca * n[1] + sa * b[1], c[2] + ca * n[2] + sa * b[2]))
    faces = []
    for i in range(segments):
        i2 = (i + 1) % segments
        for j in range(sides):
            j2 = (j + 1) % sides
            a, b_, c_, d = i * sides + j, i2 * sides + j, i2 * sides + j2, i * sides + j2
            faces.append((a, c_, b_))  # wound so cross(e1, e2) points out of the tube
            faces.append((a, d, c_))
    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    with open(out, "w", newline="\n") as f:
        f.write("# (%d,%d) torus knot, %d vertices, %d triangles, generated by tools/gen_mesh.py\n" % (P, Q, len(verts), len(faces)))
        for v in verts:
            f.write("v %.5f %.5f %.5f\n" % v)
        for a, b_, c_ in faces:
            f.write("f %d %d %d\n" % (a + 1, b_ + 1, c_ + 1))
    print("wrote %s: %d vertices, %d triangles" % (out, len(verts), len(faces)))


if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join("assets", "models", "torus_knot.obj")
    seg = int(sys.argv[2]) if len(sys.argv) > 2 else 360
    sides = int(sys.argv[3]) if len(sys.argv) > 3 else 24
    main(out, seg, sides)
